const normalize = (value: string) => String(value || '').trim().toLowerCase()

const getSearchText = (item: ToolItem) =>
  [item.title, item.desc, item.category, ...(item.keywords || [])].join(' ').toLowerCase()

export const searchTools = (keyword: string): ToolItem[] => {
  const query = normalize(keyword)
  if (!query) return toolCatalog
  return toolCatalog.filter((item) => getSearchText(item).includes(query))
}
